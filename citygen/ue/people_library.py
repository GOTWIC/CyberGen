"""LG1: lifegen's people library, built in the user's project (stdlib and `unreal` only).

    UnrealEditor-Cmd PROJECT.uproject -run=pythonscript -script=citygen/ue/people_library.py
        -AllowCommandletRendering -NoMetaHumanAccountPortalLoginFallback
        (env CITYGEN_UE_JOB: {result, spec, hash, manifest}; `citygen/unreal_people.py`)

The spec is `lifegen/library.py`'s. Every step keeps what an earlier run made with the same
spec (an asset's `cg.people` metadata names the hash of what made it), so a run that stops
(a cloud request refused, the machine restarted) goes on where it was:

1. **characters**: each a MetaHuman Character duplicated from its preset (the engine's
   optional MetaHuman content), its face model's coefficients blended toward a second preset,
   its body's constraints set (height, chest, waist, hips), its skin tone; the preset's hair,
   eyebrows and outfit kept.
2. **rig**: Epic's MetaHuman cloud service rigs it (joints only: the crowd needs no facial
   blend shapes), on the user's saved sign-in; a refusal stops the build and says what is
   missing.
3. **textures**: the skin's texture sources (2k) from the same service.
4. **assemble**: the creator's Optimized build (`spec.pipeline`) into
   `<content>/Built/<id>`: the face and body skeletal meshes, the groom and outfit assets,
   their materials, and the actor Blueprint the creator makes.
5. **clips**: the sample's walks and idles retargeted onto the MetaHuman body skeleton
   (IK Rig's batch retarget, its rigs generated by script), their notifies stripped, each
   walk's speed measured from its root motion.
6. **mid**: each character's body (a low LOD of its face and body, its outfit) as one static
   mesh with its walk baked into bone textures (AnimToTexture, bone mode), its material
   slots on lifegen's mid material (skin, cloth and hair colors from per-instance data).
7. **far**: an impostor sheet per character, the baked walk drawn from `views` directions at
   `frames` frames into one texture, on lifegen's card material.
8. **manifest**: what the runtime needs, as `library.json`.
"""

