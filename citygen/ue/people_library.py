"""LG1: lifegen's people library, built in the user's project (stdlib and `unreal` only).

    UnrealEditor-Cmd PROJECT.uproject -run=pythonscript -script=citygen/ue/people_library.py
        -AllowCommandletRendering -NoMetaHumanAccountPortalLoginFallback
        (env CITYGEN_UE_JOB: {result, spec, hash, manifest}; `citygen/unreal_people.py`)

The spec is `lifegen/library.py`'s. Every step keeps what an earlier run made with the same
spec (an asset's `cg.people` metadata names the hash of what made it), so a run that stops
(a cloud request refused, the machine restarted) goes on where it was:

1. **characters**: each a MetaHuman Character duplicated from its preset (the engine's
   optional MetaHuman content), its face model's coefficients blended toward a second preset,
   its body's constraints set (height, chest, waist, hips), its skin tone; the preset's hair,
   eyebrows and outfit kept.
2. **rig**: Epic's MetaHuman cloud service rigs it (joints only: the crowd needs no facial
   blend shapes), on the user's saved sign-in; a refusal stops the build and says what is
   missing.
3. **textures**: the skin's texture sources (2k) from the same service.
4. **assemble**: the creator's Optimized build (`spec.pipeline`) into
   `<content>/Built/<id>`: the face and body skeletal meshes, the groom and outfit assets,
   their materials, and the actor Blueprint the creator makes.
5. **clips**: the sample's walks and idles retargeted onto the MetaHuman body skeleton
   (IK Rig's batch retarget, its rigs generated by script), their notifies stripped, each
   walk's speed measured from its root motion.
6. **mid**: each character's body (a low LOD of its face and body, its outfit) as one static
   mesh with its walk baked into bone textures (AnimToTexture, bone mode), its material
   slots on lifegen's mid material (skin, cloth and hair colors from per-instance data).
7. **far**: an impostor sheet per character, the baked walk drawn from `views` directions at
   `frames` frames into one texture, on lifegen's card material.
8. **manifest**: what the runtime needs, as `library.json`.
"""

import json
import math
import os
import time
import traceback

import unreal

JOB = json.load(open(os.environ["CITYGEN_UE_JOB"], encoding="utf-8"))
SPEC = JOB["spec"]
HASH = JOB["hash"]
ROOT = SPEC["content"]
EAL = unreal.EditorAssetLibrary
AT = unreal.AssetToolsHelpers.get_asset_tools()
R = {"ok": False, "steps": {}, "characters": {}, "hash": HASH, "missing": []}
T0 = time.time()


def log(msg):
    unreal.log(f"CITYGEN_PEOPLE {msg}")


def save_result():
    R["wall_in_editor_s"] = round(time.time() - T0, 1)
    with open(JOB["result"], "w", encoding="utf-8") as f:
        json.dump(R, f, indent=1, default=str)


def meta(asset, key="cg.people"):
    try:
        return EAL.get_metadata_tag(asset, key) or ""
    except Exception:                                               # noqa: BLE001
        return ""


def tag(asset, value, key="cg.people"):
    EAL.set_metadata_tag(asset, key, value)
    EAL.save_loaded_asset(asset, only_if_is_dirty=False)


def sub():
    return unreal.get_editor_subsystem(unreal.MetaHumanCharacterEditorSubsystem)


def edit(ch):
    s = sub()
    if not s.is_object_added_for_editing(ch):
        if not s.try_add_object_to_edit(ch):
            raise RuntimeError(f"{ch.get_name()}: the creator would not open it for editing")
    return s


def char_key(c):
    return json.dumps(c, sort_keys=True)


def char_hash(c):
    import hashlib
    return hashlib.sha256(char_key(c).encode("utf-8")).hexdigest()[:16]


def char_path(c):
    return f"{ROOT}/Characters/MHC_{c['id']}"


# --- 1. characters --------------------------------------------------------------------------

def make_character(c):
    path = char_path(c)
    want = char_hash(c)
    have = unreal.load_asset(path) if EAL.does_asset_exist(path) else None
    if have is not None and meta(have).startswith(want):
        return have, False
    if have is not None:
        sub().remove_object_to_edit(have) if sub().is_object_added_for_editing(have) else None
        EAL.delete_asset(path)
    src = unreal.load_asset(f"{SPEC['presets']}/{c['preset']}.{c['preset']}")
    other = unreal.load_asset(f"{SPEC['presets']}/{c['face_with']}.{c['face_with']}")
    if src is None or other is None:
        raise RuntimeError(f"no preset {c['preset']} or {c['face_with']} (the engine's "
                           "optional MetaHuman content)")
    ch = AT.duplicate_asset(f"MHC_{c['id']}", f"{ROOT}/Characters", src)
    s = edit(ch)
    edit(other)
    # the face: the first preset's face model moved toward the second's
    a = list(s.get_face_model_coefficients(ch))
    b = list(s.get_face_model_coefficients(other))
    if a and len(a) == len(b):
        w = float(c["face_blend"])
        s.set_face_model_coefficients(ch, [(1.0 - w) * x + w * y for x, y in zip(a, b)])
        s.commit_face_state(ch)
    # the body: height, then the build round the preset's own measurements
    cons = list(s.get_body_constraints(ch, False))
    for k in cons:
        n = str(k.get_editor_property("name")).lower()
        lo, hi = k.get_editor_property("min_measurement"), k.get_editor_property("max_measurement")
        if n == "height":
            k.set_editor_property("is_active", True)
            k.set_editor_property("target_measurement",
                                  max(lo, min(hi, float(c["height_cm"]))))
        elif n in c["build"]:
            cur = k.get_editor_property("target_measurement")
            k.set_editor_property("is_active", True)
            k.set_editor_property("target_measurement",
                                  max(lo, min(hi, cur * (1.0 + float(c["build"][n])))))
    s.set_body_constraints(ch, cons)
    s.commit_body_state(ch)
    # the skin: its tone on the creator's picker, the texture sources at 2k
    skin = ch.get_editor_property("skin_settings")
    sp = skin.get_editor_property("skin")
    sp.set_editor_property("u", float(c["skin"][0]))
    sp.set_editor_property("v", float(c["skin"][1]))
    skin.set_editor_property("skin", sp)
    s.commit_skin_settings(ch, skin)
    tag(ch, f"{want} made")
    return ch, True


# --- 2 and 3. Epic's cloud: the rig and the skin's texture sources ---------------------------

def rig(ch):
    s = edit(ch)
    p = unreal.MetaHumanCharacterAutoRiggingRequestParams()
    p.set_editor_property("rig_type", unreal.MetaHumanRigType.JOINTS_ONLY)
    p.set_editor_property("report_progress", False)
    p.set_editor_property("blocking", True)
    s.request_auto_rigging(ch, p)


def textures(ch):
    s = edit(ch)
    p = unreal.MetaHumanCharacterTextureRequestParams()
    p.set_editor_property("report_progress", False)
    p.set_editor_property("blocking", True)
    s.request_texture_sources(ch, p)


# --- 4. assembly ----------------------------------------------------------------------------

def built_path(c):
    return f"{ROOT}/Built/{c['id']}"


def assemble(ch, c):
    s = edit(ch)
    if not s.can_build_meta_human(ch, True):
        raise RuntimeError(f"{c['id']}: not ready for assembly (rig or textures missing)")
    pr = unreal.MetaHumanCharacterEditorBuildParameters()
    pipe, quality = SPEC["pipeline"]
    pr.set_editor_property("pipeline_type", getattr(unreal.MetaHumanDefaultPipelineType, pipe))
    pr.set_editor_property("pipeline_quality", getattr(unreal.MetaHumanQualityLevel, quality))
    pr.set_editor_property("absolute_build_path", built_path(c))
    pr.set_editor_property("name_override", c["id"])
    s.build_meta_human(ch, pr)
    made = EAL.list_assets(built_path(c), recursive=True)
    if not made:
        raise RuntimeError(f"{c['id']}: the build made nothing")
    EAL.save_directory(built_path(c), only_if_is_dirty=True, recursive=True)
    return made


def step_characters():
    out = {}
    for c in SPEC["characters"]:
        rec = R["characters"].setdefault(c["id"], {})
        t = time.time()
        ch, made = make_character(c)
        rec["made"] = made
        st = meta(ch)
        if "rigged" not in st and "textured" not in st and "built" not in st:
            rig(ch)
            tag(ch, f"{char_hash(c)} rigged")
            rec["rig_s"] = round(time.time() - t, 1)
            st = meta(ch)
        if "textured" not in st and "built" not in st:
            textures(ch)
            if not sub().can_build_meta_human(ch, True):
                R["missing"].append("Epic's MetaHuman cloud service returned no rig or "
                                    f"textures for {c['id']} (the editor's sign-in)")
                raise RuntimeError(f"{c['id']}: no rig or textures from the cloud")
            tag(ch, f"{char_hash(c)} textured")
            st = meta(ch)
        if "built" not in st or not EAL.does_directory_exist(built_path(c)):
            rec["assets"] = assemble(ch, c)
            tag(ch, f"{char_hash(c)} built")
        rec["s"] = round(time.time() - t, 1)
        out[c["id"]] = rec
        log(f"character {c['id']} ({c['preset']}) {rec}")
        save_result()
    return {"count": len(out)}


def built_meshes(c):
    """The assembled character's skeletal meshes by role: body, face and the rest (outfit,
    hair cards), from the build's folder."""
    out = {"body": None, "face": None, "other": []}
    for p in sorted(EAL.list_assets(built_path(c), recursive=True)):
        a = unreal.load_asset(p)
        if not isinstance(a, unreal.SkeletalMesh):
            continue
        n = p.rsplit("/", 1)[-1].lower()
        if out["body"] is None and "body" in n:
            out["body"] = a
        elif out["face"] is None and ("face" in n or "head" in n):
            out["face"] = a
        else:
            out["other"].append(a)
    return out


def find_body(c):
    return built_meshes(c)["body"]


# --- 5. the clips: the sample's walks and idles onto the MetaHuman body ----------------------

def _ik_rig(name, mesh, folder):
    path = f"{folder}/{name}"
    if EAL.does_asset_exist(path):
        EAL.delete_asset(path)
    rig_ = AT.create_asset(name, folder, unreal.IKRigDefinition, unreal.IKRigDefinitionFactory())
    ctl = unreal.IKRigController.get_controller(rig_)
    ctl.set_skeletal_mesh(mesh)
    ctl.apply_auto_generated_retarget_definition()
    EAL.save_loaded_asset(rig_)
    return rig_


def clip_speed(seq):
    """How fast a clip walks at its own rate (m/s): its root's travel over its length (the
    sample's loops carry root motion), else its pelvis's."""
    AL = unreal.AnimationLibrary
    n = AL.get_num_frames(seq)
    length = AL.get_sequence_length(seq)
    if n < 2 or length <= 0:
        return 0.0
    for bone in ("root", "pelvis"):
        try:
            a = AL.get_bone_pose_for_frame(seq, bone, 0, False).translation
            b = AL.get_bone_pose_for_frame(seq, bone, n - 1, False).translation
        except Exception:                                           # noqa: BLE001
            continue
        d = math.hypot(b.x - a.x, b.y - a.y) / 100.0
        if d > 0.2:
            return round(d / length * n / (n - 1), 3) if bone == "root" else round(d / length, 3)
    return 0.0


def step_clips():
    """The sample's clips retargeted onto the first character's body skeleton (every
    character's body shares it); the source mesh and its IK rig come with the sample."""
    folder = f"{ROOT}/Anim"
    body = None
    for c in SPEC["characters"]:
        body = find_body(c)
        if body is not None:
            break
    if body is None:
        raise RuntimeError("no assembled body to retarget the clips onto")
    src_mesh = unreal.load_asset(SPEC["gas"]["mesh"])
    if src_mesh is None:
        R["missing"].append(f"{SPEC['gas']['mesh']} (the Game Animation Sample's mannequin)")
        raise RuntimeError("the sample's mannequin is not in the project (migrate first)")
    want = HASH
    out = {}
    have = {k: unreal.load_asset(f"{folder}/A_{k}") for k in SPEC["clips"]
            if EAL.does_asset_exist(f"{folder}/A_{k}")}
    if len(have) == len(SPEC["clips"]) and all(meta(a) == want for a in have.values()):
        return {k: {"anim": f"{folder}/A_{k}", "speed": float(meta(a, "cg.speed") or 0)}
                for k, a in have.items()}
    src_rig = _ik_rig("IK_GasSource", src_mesh, f"{folder}/Rigs")
    dst_rig = _ik_rig("IK_PeopleBody", body, f"{folder}/Rigs")
    rpath = f"{folder}/Rigs/RTG_GasToPeople"
    if EAL.does_asset_exist(rpath):
        EAL.delete_asset(rpath)
    rtg = AT.create_asset("RTG_GasToPeople", f"{folder}/Rigs", unreal.IKRetargeter,
                          unreal.IKRetargetFactory())
    rc = unreal.IKRetargeterController.get_controller(rtg)
    S, T = unreal.RetargetSourceOrTarget.SOURCE, unreal.RetargetSourceOrTarget.TARGET
    rc.set_ik_rig(S, src_rig)
    rc.set_ik_rig(T, dst_rig)
    rc.set_preview_mesh(S, src_mesh)
    rc.set_preview_mesh(T, body)
    for fn, args in (("add_default_ops", ()), ("auto_map_chains", None),
                     ("auto_align_all_bones", (T,))):
        if hasattr(rc, fn):
            try:
                if fn == "auto_map_chains":
                    rc.auto_map_chains(unreal.AutoMapChainType.FUZZY, True)
                else:
                    getattr(rc, fn)(*args)
            except Exception as e:                                  # noqa: BLE001
                log(f"retargeter {fn}: {e}")
    EAL.save_loaded_asset(rtg)
    for k, src in SPEC["clips"].items():
        seq = unreal.load_asset(src)
        if seq is None:
            R["missing"].append(f"{src} (the Game Animation Sample's clip)")
            raise RuntimeError(f"no clip {src} in the project")
        dst = f"{folder}/A_{k}"
        if EAL.does_asset_exist(dst):
            EAL.delete_asset(dst)
        made = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
            [EAL.find_asset_data(src)], src_mesh, body, rtg, search="", replace="",
            prefix="", suffix="_People", target_path=folder)
        got = [str(x.get_editor_property("package_name")) for x in made]
        seq2 = unreal.load_asset(got[0]) if got else None
        if seq2 is None:
            raise RuntimeError(f"the retarget of {src} made nothing")
        EAL.rename_asset(got[0], dst)
        seq2 = unreal.load_asset(dst)
        try:
            unreal.AnimationLibrary.remove_all_animation_notify_tracks(seq2)
        except Exception as e:                                      # noqa: BLE001
            log(f"notifies of {k}: {e}")
        sp = clip_speed(seq) if k.startswith("walk") else 0.0
        EAL.set_metadata_tag(seq2, "cg.speed", str(sp))
        tag(seq2, want)
        out[k] = {"anim": dst, "speed": sp,
                  "length_s": round(unreal.AnimationLibrary.get_sequence_length(seq2), 3)}
    return out


STEPS = [("characters", step_characters), ("clips", step_clips)]


def main():
    for name, fn in STEPS:
        if name not in JOB.get("steps", [n for n, _ in STEPS]):
            continue
        t = time.time()
        try:
            R["steps"][name] = {"ok": True, "result": fn()}
        except Exception as e:                                      # noqa: BLE001
            R["steps"][name] = {"ok": False, "error": f"{type(e).__name__}: {e}",
                                "trace": traceback.format_exc()[-3000:]}
            R["error"] = f"{name}: {type(e).__name__}: {e}"
            log(f"step {name} FAILED: {e}")
            save_result()
            return
        R["steps"][name]["s"] = round(time.time() - t, 1)
        log(f"step {name} done in {R['steps'][name]['s']} s")
        save_result()
    R["ok"] = True
    save_result()


main()
unreal.log("CITYGEN_UE_DONE")
