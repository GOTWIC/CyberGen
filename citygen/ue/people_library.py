TEX_PREFER = ("basecolor baked", "basecolor", "base color", "albedo", "diffuse", "texture")
TEX_SKIP = ("normal", "mask", "cavity", "srmf", "scatter", "animated", "detail", "macro",
            "micro", "n3c", "flow", "ao", "print", "pill", "stitch", "distort", "wrinkle")
