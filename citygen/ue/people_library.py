def step_manifest():
    # (LG2: an entry per look, the runtime's unit: its character's body and face, the look's
    # garments, its hair unless the look covers it, its mid mesh and card)
    chars = []
    for c, lk in look_list():
        parts = built_meshes(c)
        rec = R["characters"][c["id"]]
        lr = R["looks"][lk["id"]]
        meshes = [m.get_path_name().split(".")[0] for m in [parts["body"], parts["face"]]
                  if m is not None] + [lr["near"]]
        hair, _ = hair_meshes(c)
        chars.append({"id": lk["id"], "character": c["id"], "index": c["index"],
                      "preset": c["preset"], "body": c["body"], "group": lk["group"],
                      "skeleton": rec["skeleton"],
                      "near": {"meshes": meshes, "hair": "" if lk.get("hide_hair") else hair},
                      "mid": lr["mid"], "far": lr["far"]})
    groups = R["clip_groups"]
    first = next(iter(groups.values()))["clips"]
    man = {"version": SPEC["version"], "hash": HASH, "content": ROOT,
           "characters": chars, "looks": True, "people": len(SPEC["characters"]),
           "garment_materials": R.get("garment_materials", {}), "walks": SPEC["walks"],
           "idles": [k for k in SPEC["clips"] if k.startswith("idle")],
           "clips": first, "clip_groups": groups,
           "far": {"card": "/Engine/BasicShapes/Plane", "size": [CARD_W_CM / 100.0,
                                                                CARD_H_CM / 100.0],
                   "views": SPEC["impostor"]["views"], "frames": SPEC["impostor"]["frames"]},
           "tiers": JOB.get("tiers") or {}, "extra_folders": []}
    os.makedirs(os.path.dirname(JOB["manifest"]), exist_ok=True)
    with open(JOB["manifest"], "w", encoding="utf-8") as f:
        json.dump(man, f, indent=1)
    yield
    return {"characters": len(chars), "groups": len(groups)}


def as_gen(fn):
    """A step as a generator (a plain function's result once)."""
    def run():
        r = fn()
        if hasattr(r, "__next__"):
            return (yield from r)
        yield
        return r
    return run


STEPS = [("characters", step_characters), ("clips", step_clips), ("bodies", step_bodies),
         ("looks", step_looks), ("mid", step_mid), ("far", step_far),
         ("manifest", step_manifest)]


def run():
    yield
    # (the editor scans the asset registry in the background at start: what an earlier run
    # made is found only once it is done)
    unreal.AssetRegistryHelpers.get_asset_registry().wait_for_completion()
    for name, fn in STEPS:
        if name not in JOB.get("steps", [n for n, _ in STEPS]):
            continue
        t = time.time()
        log(f"step {name} begins")
        try:
            res = yield from fn()
            R["steps"][name] = {"ok": True, "result": res}
        except Exception as e:                                      # noqa: BLE001
            R["steps"][name] = {"ok": False, "error": f"{type(e).__name__}: {e}",
                                "trace": traceback.format_exc()[-3000:]}
            R["error"] = f"{name}: {type(e).__name__}: {e}"
            log(f"step {name} FAILED: {e}")
            save_result()
            return
        R["steps"][name]["s"] = round(time.time() - t, 1)
        log(f"step {name} done in {R['steps'][name]['s']} s")
        save_result()
        if R.get("restart"):
            return
    R["ok"] = True
    save_result()


# --- the tick loop (the full editor: texture graphs and captures need it) -------------------

GEN = run()
HANDLE = None
BUSY = [False]


def finish():
    save_result()
    print("CITYGEN_UE_DONE " + json.dumps({"ok": R["ok"]}))
    unreal.unregister_slate_post_tick_callback(HANDLE)
    unreal.SystemLibrary.quit_editor()


def tick(dt):
    if BUSY[0]:
        return
    BUSY[0] = True
    try:
        next(GEN)
    except StopIteration:
        finish()
    except Exception:                                               # noqa: BLE001
        R["error"] = traceback.format_exc()
        unreal.log_error(R["error"])
        finish()
    finally:
        BUSY[0] = False


HANDLE = unreal.register_slate_post_tick_callback(tick)
