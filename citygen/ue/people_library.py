"""LG1: lifegen's people library, built in the user's project (stdlib and `unreal` only).

    UnrealEditor-Cmd PROJECT.uproject -run=pythonscript -script=citygen/ue/people_library.py
        -AllowCommandletRendering -NoMetaHumanAccountPortalLoginFallback
        (env CITYGEN_UE_JOB: {result, spec, hash, manifest}; `citygen/unreal_people.py`)

The spec is `lifegen/library.py`'s. Every step keeps what an earlier run made with the same
spec (an asset's `cg.people` metadata names the hash of what made it), so a run that stops
(a cloud request refused, the machine restarted) goes on where it was:

1. **characters**: each a MetaHuman Character duplicated from its preset (the engine's
   optional MetaHuman content), its face model's coefficients blended toward a second preset,
   its body's constraints set (height, chest, waist, hips), its skin tone; the preset's hair,
   eyebrows and outfit kept.
2. **rig**: Epic's MetaHuman cloud service rigs it (joints only: the crowd needs no facial
   blend shapes), on the user's saved sign-in; a refusal stops the build and says what is
   missing.
3. **textures**: the skin's texture sources (2k) from the same service.
4. **assemble**: the creator's Optimized build (`spec.pipeline`) into
   `<content>/Built/<id>`: the face and body skeletal meshes, the groom and outfit assets,
   their materials, and the actor Blueprint the creator makes.
5. **bodies** (LG2): each character's body, plain outfit and face at LOD 0 in the reference
   pose with its bones, as JSON for the Blender stage (`lifegen/blender/garments.py`), which
   cuts and drapes each character's garments on them (run by the venv between editor runs).
6. **looks** (LG2): the textiles imported, the garment material and an instance per textile,
   and per look its garments as a skeletal mesh on the body's skeleton (LOD 0 and 1), the
   weights taken from the body and its plain outfit (the outfit where it is nearer: the body
   has no skin under it), accessories held to their bone.
7. **clips**: the sample's walks and idles retargeted onto the MetaHuman body skeleton
   (IK Rig's batch retarget, its rigs generated by script), their notifies stripped, each
   walk's speed measured from its root motion.
8. **mid**: each look (a low LOD of its character's face and body, its garments' mid mesh)
   as one static mesh with its walk baked into bone textures (AnimToTexture, bone mode), its material
   slots on lifegen's mid material (skin, cloth and hair colors from per-instance data).
9. **far**: an impostor sheet per look, the baked walk drawn from `views` directions at
   `frames` frames into one texture, on lifegen's card material.
10. **manifest**: what the runtime needs, as `library.json` (an entry per look).
"""

import json
import math
import os
import time
import traceback

import unreal

JOB = json.load(open(os.environ["CITYGEN_UE_JOB"], encoding="utf-8"))
SPEC = JOB["spec"]
HASH = JOB["hash"]
ROOT = SPEC["content"]
EAL = unreal.EditorAssetLibrary
AT = unreal.AssetToolsHelpers.get_asset_tools()
R = {"ok": False, "steps": {}, "characters": {}, "hash": HASH, "missing": []}
T0 = time.time()


def log(msg):
    unreal.log(f"CITYGEN_PEOPLE {msg}")


def save_result():
    R["wall_in_editor_s"] = round(time.time() - T0, 1)
    with open(JOB["result"], "w", encoding="utf-8") as f:
        json.dump(R, f, indent=1, default=str)


def meta(asset, key="cg.people"):
    try:
        return EAL.get_metadata_tag(asset, key) or ""
    except Exception:                                               # noqa: BLE001
        return ""


def tag(asset, value, key="cg.people"):
    EAL.set_metadata_tag(asset, key, value)
    EAL.save_loaded_asset(asset, only_if_is_dirty=False)


def sub():
    return unreal.get_editor_subsystem(unreal.MetaHumanCharacterEditorSubsystem)


def edit(ch):
    s = sub()
    if not s.is_object_added_for_editing(ch):
        if not s.try_add_object_to_edit(ch):
            raise RuntimeError(f"{ch.get_name()}: the creator would not open it for editing")
    return s


def char_key(c):
    return json.dumps(c, sort_keys=True)


def char_hash(c):
    import hashlib
    return hashlib.sha256(char_key(c).encode("utf-8")).hexdigest()[:16]


def char_path(c):
    return f"{ROOT}/Characters/MHC_{c['id']}"


def _of(r, cls):
    """The value of type `cls` among a GeometryScript call's returns (an array for `list`;
    the last int for `int`, past the bools)."""
    xs = r if isinstance(r, tuple) else (r,)
    if cls is list:
        for x in xs:
            if isinstance(x, (list, unreal.Array)):
                return list(x)
        return None
    if cls is int:
        ints = [x for x in xs if isinstance(x, int) and not isinstance(x, bool)]
        return ints[-1] if ints else None
    for x in xs:
        if isinstance(x, cls):
            return x
    return None


def look_list():
    """Every look of the library, in order: (character, look)."""
    out = []
    for c, ls in zip(SPEC["characters"], SPEC.get("looks") or []):
        for lk in ls:
            out.append((c, lk))
    return out


# --- 1. characters --------------------------------------------------------------------------

def make_character(c):
    path = char_path(c)
    want = char_hash(c)
    have = unreal.load_asset(path) if EAL.does_asset_exist(path) else None
    if have is not None and meta(have).startswith(want):
        return have, False
    if have is not None:
        sub().remove_object_to_edit(have) if sub().is_object_added_for_editing(have) else None
        EAL.delete_asset(path)
    src = unreal.load_asset(f"{SPEC['presets']}/{c['preset']}.{c['preset']}")
    other = unreal.load_asset(f"{SPEC['presets']}/{c['face_with']}.{c['face_with']}")
    if src is None or other is None:
        raise RuntimeError(f"no preset {c['preset']} or {c['face_with']} (the engine's "
                           "optional MetaHuman content)")
    ch = AT.duplicate_asset(f"MHC_{c['id']}", f"{ROOT}/Characters", src)
    s = edit(ch)
    edit(other)
    # the face: the first preset's face model moved toward the second's
    a = list(s.get_face_model_coefficients(ch))
    b = list(s.get_face_model_coefficients(other))
    if a and len(a) == len(b):
        w = float(c["face_blend"])
        s.set_face_model_coefficients(ch, [(1.0 - w) * x + w * y for x, y in zip(a, b)])
        s.commit_face_state(ch)
    # the body: height, then the build round the preset's own measurements
    cons = list(s.get_body_constraints(ch, False))
    for k in cons:
        n = str(k.get_editor_property("name")).lower()
        lo, hi = k.get_editor_property("min_measurement"), k.get_editor_property("max_measurement")
        if n == "height":
            k.set_editor_property("is_active", True)
            k.set_editor_property("target_measurement",
                                  max(lo, min(hi, float(c["height_cm"]))))
        elif n in c["build"]:
            cur = k.get_editor_property("target_measurement")
            k.set_editor_property("is_active", True)
            k.set_editor_property("target_measurement",
                                  max(lo, min(hi, cur * (1.0 + float(c["build"][n])))))
    s.set_body_constraints(ch, cons)
    s.commit_body_state(ch)
    # the skin: its tone on the creator's picker, the texture sources at 2k
    skin = ch.get_editor_property("skin_settings")
    sp = skin.get_editor_property("skin")
    sp.set_editor_property("u", float(c["skin"][0]))
    sp.set_editor_property("v", float(c["skin"][1]))
    skin.set_editor_property("skin", sp)
    s.commit_skin_settings(ch, skin)
    tag(ch, f"{want} made")
    return ch, True


# --- 2 and 3. Epic's cloud: the rig and the skin's texture sources ---------------------------

def rig(ch):
    s = edit(ch)
    p = unreal.MetaHumanCharacterAutoRiggingRequestParams()
    p.set_editor_property("rig_type", unreal.MetaHumanRigType.JOINTS_ONLY)
    p.set_editor_property("report_progress", False)
    p.set_editor_property("blocking", True)
    s.request_auto_rigging(ch, p)


def textures(ch):
    s = edit(ch)
    p = unreal.MetaHumanCharacterTextureRequestParams()
    p.set_editor_property("report_progress", False)
    p.set_editor_property("blocking", True)
    s.request_texture_sources(ch, p)


# --- 4. assembly ----------------------------------------------------------------------------

def built_path(c):
    return f"{ROOT}/Built/{c['id']}"


def assemble(ch, c):
    s = edit(ch)
    if not s.can_build_meta_human(ch, True):
        raise RuntimeError(f"{c['id']}: not ready for assembly (rig or textures missing)")
    pr = unreal.MetaHumanCharacterEditorBuildParameters()
    pipe, quality = SPEC["pipeline"]
    pr.set_editor_property("pipeline_type", getattr(unreal.MetaHumanDefaultPipelineType, pipe))
    pr.set_editor_property("pipeline_quality", getattr(unreal.MetaHumanQualityLevel, quality))
    pr.set_editor_property("absolute_build_path", built_path(c))
    pr.set_editor_property("name_override", c["id"])
    s.build_meta_human(ch, pr)
    made = EAL.list_assets(built_path(c), recursive=True)
    if not made:
        raise RuntimeError(f"{c['id']}: the build made nothing")
    EAL.save_directory(built_path(c), only_if_is_dirty=True, recursive=True)
    return made


BUILT = [0]
PER_RUN = int(JOB.get("per_run", 6))


def step_characters():
    out = {}
    for c in SPEC["characters"]:
        rec = R["characters"].setdefault(c["id"], {})
        t = time.time()
        ch, made = make_character(c)
        rec["made"] = made
        st = meta(ch)
        if "rigged" not in st and "textured" not in st and "built" not in st:
            rig(ch)
            tag(ch, f"{char_hash(c)} rigged")
            rec["rig_s"] = round(time.time() - t, 1)
            st = meta(ch)
        if "textured" not in st and "built" not in st:
            textures(ch)
            if not sub().can_build_meta_human(ch, True):
                R["missing"].append("Epic's MetaHuman cloud service returned no rig or "
                                    f"textures for {c['id']} (the editor's sign-in)")
                raise RuntimeError(f"{c['id']}: no rig or textures from the cloud")
            tag(ch, f"{char_hash(c)} textured")
            st = meta(ch)
        if "built" not in st or not EAL.does_directory_exist(built_path(c)):
            rec["assets"] = len(assemble(ch, c))
            tag(ch, f"{char_hash(c)} built")
            BUILT[0] += 1
        rec["s"] = round(time.time() - t, 1)
        out[c["id"]] = rec
        log(f"character {c['id']} ({c['preset']}) {rec}")
        save_result()
        yield
        if BUILT[0] >= PER_RUN and c is not SPEC["characters"][-1]:
            # (the editor keeps what each assembly loaded: past a few characters its memory
            # outgrows the machine's, so the run ends here and the next goes on)
            R["restart"] = True
            log(f"restart after {BUILT[0]} characters")
            return {"count": len(out), "restart": True}
    return {"count": len(out)}


def built_meshes(c):
    """The assembled character's skeletal meshes by role: body, face and the rest (outfit,
    hair cards), from the build's folder."""
    out = {"body": None, "face": None, "other": []}
    for p in sorted(EAL.list_assets(built_path(c), recursive=True)):
        a = unreal.load_asset(p)
        if not isinstance(a, unreal.SkeletalMesh):
            continue
        n = p.rsplit("/", 1)[-1].lower()
        if out["body"] is None and "body" in n:
            out["body"] = a
        elif out["face"] is None and ("face" in n or "head" in n):
            out["face"] = a
        else:
            out["other"].append(a)
    return out


def find_body(c):
    return built_meshes(c)["body"]


# --- LG2 5. bodies: what the Blender stage drapes the garments on ---------------------------

def dyn_skeletal(mesh, lod=0):
    dm = unreal.DynamicMesh()
    rl = unreal.GeometryScriptMeshReadLOD()
    rl.set_editor_property("lod_index", _lod(mesh, lod))
    _gs("copy_mesh_from_skeletal_mesh")(mesh, dm, unreal.GeometryScriptCopyMeshFromAssetOptions(), rl)
    return dm


def dump_mesh(dm):
    """A dynamic mesh's positions, triangles, material ids, each vertex's largest bone and its
    bones (component space reference pose), as the Blender stage reads them."""
    Q, LU = unreal.GeometryScript_MeshQueries, unreal.GeometryScript_List
    pos = []
    for v in LU.convert_vector_list_to_array(_of(Q.get_all_vertex_positions(dm, False),
                                                 unreal.GeometryScriptVectorList)):
        pos += [round(v.x, 3), round(v.y, 3), round(v.z, 3)]
    tris = []
    for k in LU.convert_triangle_list_to_array(_of(Q.get_all_triangle_indices(dm, False),
                                                   unreal.GeometryScriptTriangleList)):
        tris += [k.x, k.y, k.z]
    mids = list(LU.convert_index_list_to_array(_of(
        unreal.GeometryScript_Materials.get_all_triangle_material_i_ds(dm),
        unreal.GeometryScriptIndexList)))
    bones = []
    for b in _of(unreal.GeometryScript_BoneWeights.get_all_bones_info(dm), list) or []:
        t = b.world_transform.translation
        bones.append({"name": str(b.name), "parent": b.parent_index,
                      "t": [round(t.x, 3), round(t.y, 3), round(t.z, 3)]})
    return {"positions": pos, "triangles": tris, "material_ids": mids, "bones": bones}


def outfit_mesh(parts):
    for m in parts["other"]:
        if "outfit" in m.get_name().lower():
            return m
    return parts["other"][0] if parts["other"] else None


def step_bodies():
    """Each character's body, plain outfit and face (LOD 0, reference pose) for the Blender
    stage; kept while the character is."""
    folder = JOB["bodies_dir"]
    os.makedirs(folder, exist_ok=True)
    n = 0
    for c in SPEC["characters"]:
        path = os.path.join(folder, f"{c['id']}.json")
        want = char_hash(c)
        if os.path.isfile(path):
            try:
                if json.load(open(path, encoding="utf-8")).get("hash") == want:
                    continue
            except ValueError:
                pass
        parts = built_meshes(c)
        rec = {"hash": want, "id": c["id"], "body": dump_mesh(dyn_skeletal(parts["body"])),
               "face": dump_mesh(dyn_skeletal(parts["face"])),
               "outfit": dump_mesh(dyn_skeletal(outfit_mesh(parts)))}
        with open(path, "w", encoding="utf-8") as f:
            json.dump(rec, f)
        n += 1
        log(f"body {c['id']} exported")
        yield
    return {"exported": n}


# --- LG2 6. looks: textiles, the garment material, each look's skeletal mesh ----------------

TEX_ROOT = f"{ROOT}/Textiles"


def import_textiles():
    """The textiles' images (`lifegen/textiles.py`, built by the venv into the job's
    `textiles_dir`) as textures: base color (sRGB), normal (OpenGL: green flipped), occlusion,
    roughness, metallic and the wear mask (linear)."""
    rec = json.load(open(os.path.join(JOB["textiles_dir"], "textiles.json"), encoding="utf-8"))
    tasks, made = [], {}
    for name in sorted(rec["textiles"]):
        for kind in ("base", "normal", "orm"):
            path = f"{TEX_ROOT}/T_{name}_{kind}"
            h = rec["textiles"][name].get("images", {}).get(kind, "")
            made[(name, kind)] = path
            if EAL.does_asset_exist(path) and meta(unreal.load_asset(path)) == h:
                continue
            t = unreal.AssetImportTask()
            t.set_editor_property("filename", os.path.join(JOB["textiles_dir"], f"{name}_{kind}.png"))
            t.set_editor_property("destination_path", TEX_ROOT)
            t.set_editor_property("destination_name", f"T_{name}_{kind}")
            t.set_editor_property("automated", True)
            t.set_editor_property("replace_existing", True)
            t.set_editor_property("save", False)
            tasks.append((t, path, kind, h))
    if tasks:
        AT.import_asset_tasks([t for t, _, _, _ in tasks])
    for _, path, kind, h in tasks:
        tex = unreal.load_asset(path)
        if tex is None:
            raise RuntimeError(f"the textile {path} did not import")
        if kind == "normal":
            tex.set_editor_property("compression_settings",
                                    unreal.TextureCompressionSettings.TC_NORMALMAP)
            tex.set_editor_property("flip_green_channel", True)
            tex.set_editor_property("srgb", False)
        elif kind == "orm":
            tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_MASKS)
            tex.set_editor_property("srgb", False)
        tex.set_editor_property("virtual_texture_streaming", False)
        EAL.set_metadata_tag(tex, "cg.people", h)
        EAL.save_loaded_asset(tex, False)
    return rec, made


def _custom(m, code, ins, out_type, x, y):
    n = MEL.create_material_expression(m, unreal.MaterialExpressionCustom, x, y)
    n.set_editor_property("code", code)
    n.set_editor_property("output_type", out_type)
    cis = []
    for k, _ in ins:
        ci = unreal.CustomInput()
        ci.set_editor_property("input_name", k)
        cis.append(ci)
    n.set_editor_property("inputs", cis)
    for k, (src, out) in ins:
        _link(src, out, n, k)
    return n


def _e(m, cls, x, y, **kw):
    n = MEL.create_material_expression(m, cls, x, y)
    for k, v in kw.items():
        n.set_editor_property(k, v)
    return n


DYE_CODE = ("float a = VC.a; float3 t = float3(1, 1, 1);\n"
            "if (a > 0.83) t = T2; else if (a > 0.5) t = T1; else if (a > 0.17) t = T0;\n")


def garment_material(sample):
    """M_CgGarment (near, skeletal): a textile's base color times the vertex color times the
    person's color for the vertex's dye channel (vertex alpha: none, 0, 1, 2; parameters
    Tint0 to Tint2), faded and grimed by Wear where the textile's wear mask says, its
    normal, occlusion, roughness and metallic, glowing by Emissive (LED trims), two-sided."""
    path = f"{ROOT}/Materials/M_CgGarment_{HASH[:8]}"
    if EAL.does_asset_exist(path) and meta(unreal.load_asset(path)) == HASH:
        return unreal.load_asset(path)
    m = _new_material(path)
    m.set_editor_property("two_sided", True)
    m.set_editor_property("used_with_skeletal_mesh", True)
    base_t, nrm_t, orm_t = sample
    base = _e(m, unreal.MaterialExpressionTextureSampleParameter2D, -1400, 0,
              parameter_name="Base", texture=base_t, sampler_type=_sampled(base_t))
    nrm = _e(m, unreal.MaterialExpressionTextureSampleParameter2D, -1400, 300,
             parameter_name="Normal", texture=nrm_t,
             sampler_type=unreal.MaterialSamplerType.SAMPLERTYPE_NORMAL)
    orm = _e(m, unreal.MaterialExpressionTextureSampleParameter2D, -1400, 600,
             parameter_name="ORM", texture=orm_t,
             sampler_type=unreal.MaterialSamplerType.SAMPLERTYPE_MASKS)
    tile = _e(m, unreal.MaterialExpressionScalarParameter, -2000, 200, parameter_name="TileM",
              default_value=0.3)
    tc = _e(m, unreal.MaterialExpressionTextureCoordinate, -2000, 0)
    uv = _custom(m, "return UV / max(Tile, 0.01);", [("UV", (tc, "")), ("Tile", (tile, ""))],
                 unreal.CustomMaterialOutputType.CMOT_FLOAT2, -1700, 100)
    for t in (base, nrm, orm):
        _link(uv, "", t, "UVs")
    vc = _e(m, unreal.MaterialExpressionVertexColor, -1400, 900)
    vc4 = _e(m, unreal.MaterialExpressionAppendVector, -1200, 900)
    _link(vc, "", vc4, "A")
    _link(vc, "A", vc4, "B")
    tints = [_e(m, unreal.MaterialExpressionVectorParameter, -1400, 1100 + 150 * k,
                parameter_name=f"Tint{k}", default_value=unreal.LinearColor(0.5, 0.5, 0.5, 1))
             for k in range(3)]
    wear = _e(m, unreal.MaterialExpressionScalarParameter, -1400, 1600, parameter_name="Wear",
              default_value=0.0)
    col = _custom(m, DYE_CODE +
                  "float3 c = B * VC.rgb * t;\n"
                  "float w = saturate(Wear * (0.4 + WM));\n"
                  "float l = dot(c, float3(0.3, 0.59, 0.11));\n"
                  "return lerp(c, lerp(c, l.xxx, 0.45) * 0.78 + 0.02, w);",
                  [("B", (base, "RGB")), ("VC", (vc4, "")), ("T0", (tints[0], "")),
                   ("T1", (tints[1], "")), ("T2", (tints[2], "")), ("Wear", (wear, "")),
                   ("WM", (orm, "A"))], unreal.CustomMaterialOutputType.CMOT_FLOAT3, -900, 400)
    MEL.connect_material_property(col, "", unreal.MaterialProperty.MP_BASE_COLOR)
    emis = _e(m, unreal.MaterialExpressionScalarParameter, -900, 700, parameter_name="Emissive",
              default_value=0.0)
    em = _e(m, unreal.MaterialExpressionMultiply, -600, 700)
    _link(col, "", em, "A")
    _link(emis, "", em, "B")
    MEL.connect_material_property(em, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    MEL.connect_material_property(nrm, "RGB", unreal.MaterialProperty.MP_NORMAL)
    rough = _e(m, unreal.MaterialExpressionMultiply, -600, 800)
    rs = _e(m, unreal.MaterialExpressionScalarParameter, -900, 900, parameter_name="RoughScale",
            default_value=1.0)
    _link(orm, "G", rough, "A")
    _link(rs, "", rough, "B")
    MEL.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
    MEL.connect_material_property(orm, "B", unreal.MaterialProperty.MP_METALLIC)
    MEL.connect_material_property(orm, "R", unreal.MaterialProperty.MP_AMBIENT_OCCLUSION)
    MEL.recompile_material(m)
    tag(m, HASH)
    return m


def garment_instances(rec, made):
    """An instance of M_CgGarment per textile (its images, its tile, LED trims glowing)."""
    tex = {k: unreal.load_asset(v) for k, v in made.items()}
    first = sorted(rec["textiles"])[0]
    master = garment_material((tex[(first, "base")], tex[(first, "normal")], tex[(first, "orm")]))
    out = {}
    for name, t in sorted(rec["textiles"].items()):
        path = f"{ROOT}/Materials/Garments/MI_{name}"
        mi = _asset(path, unreal.MaterialInstanceConstant, unreal.MaterialInstanceConstantFactoryNew())
        MEL.set_material_instance_parent(mi, master)
        for kind, prm in (("base", "Base"), ("normal", "Normal"), ("orm", "ORM")):
            MEL.set_material_instance_texture_parameter_value(mi, prm, tex[(name, kind)])
        MEL.set_material_instance_scalar_parameter_value(mi, "TileM", float(t["tile"]))
        MEL.set_material_instance_scalar_parameter_value(
            mi, "Emissive", 8.0 if t["kind"] == "emissive" else 0.0)
        EAL.save_loaded_asset(mi)
        out[name] = mi
    return out


def dyn_from_json(rec):
    """A dynamic mesh from the Blender stage's JSON (`garments.export`): vertices, normals,
    uv0, colors, triangles, each triangle's slot."""
    V, N, U, C, T = rec["vertices"], rec["normals"], rec["uv0"], rec["colors"], rec["triangles"]
    nv = len(V) // 3
    buf = unreal.GeometryScriptSimpleMeshBuffers()
    buf.set_editor_property("vertices", [unreal.Vector(V[3 * i], V[3 * i + 1], V[3 * i + 2])
                                         for i in range(nv)])
    buf.set_editor_property("normals", [unreal.Vector(N[3 * i], N[3 * i + 1], N[3 * i + 2])
                                        for i in range(nv)])
    buf.set_editor_property("uv0", [unreal.Vector2D(U[2 * i], U[2 * i + 1]) for i in range(nv)])
    buf.set_editor_property("vertex_colors", [unreal.LinearColor(C[4 * i], C[4 * i + 1],
                                                                 C[4 * i + 2], C[4 * i + 3])
                                              for i in range(nv)])
    buf.set_editor_property("triangles", [unreal.IntVector(T[3 * k], T[3 * k + 1], T[3 * k + 2])
                                          for k in range(len(T) // 3)])
    dm = unreal.DynamicMesh()
    r = unreal.GeometryScript_MeshEdits.append_buffers_to_mesh(dm, buf, 0)
    tl = _of(r, unreal.GeometryScriptIndexList)
    unreal.GeometryScript_Materials.enable_material_i_ds(dm)
    ids = unreal.GeometryScriptIndexList()
    ids = unreal.GeometryScript_List.convert_array_to_index_list(rec["mats"]) \
        if hasattr(unreal.GeometryScript_List, "convert_array_to_index_list") else ids
