def mid_mesh(c, clips, lk):
    """A look as one static mesh (its character's body and face at low LODs, its garments'
    mid mesh, the hair's helmet unless the look covers the hair), its walk baked into bone
    textures against the body, the body's slots on M_CgPersonMid, the garments' on
    M_CgPersonMidCloth (and _Glow)."""
    lid = lk["id"]
    folder = f"{ROOT}/Mid/{lid}"
    sm_path = f"{folder}/SM_{lid}_Mid"
    da_path = f"{folder}/DA_{lid}_Mid"
    if EAL.does_asset_exist(sm_path) and EAL.does_asset_exist(da_path) and \
            meta(unreal.load_asset(da_path)) == HASH and \
            unreal.load_asset(da_path).get_editor_property("bone_position_texture") is not None:
        da = unreal.load_asset(da_path)
        return {"mesh": sm_path, "start": 0, "end": int(da.get_editor_property("num_frames")) - 1,
                "fps": float(SPEC["far"]["fps"]), "data": da_path,
                "cycle_s": float(meta(da, "cg.cycle") or 1.0)}
    parts = built_meshes(c)
    body = parts["body"]
    lod = int(SPEC["far"]["lod"])
    pieces = [(body, lod - 2), (parts["face"], lod - 2)]
    _, helmet = hair_meshes(c)
    helm = unreal.load_asset(helmet) if helmet and not lk.get("hide_hair") else None
    rec = json.load(open(os.path.join(JOB["garments_dir"], c["id"], f"{lid}.mid.json"),
                         encoding="utf-8"))
    cloth = [mid_cloth_material(False), mid_cloth_material(True)]
    # (the helmet's own slots take the hair's color: its material has none to read)
    helm_mats = {m.get_editor_property("material_interface").get_path_name()
                 for m in (helm.get_editor_property("static_materials") if helm else [])
                 if m.get_editor_property("material_interface") is not None}
    mesh = assemble_static(sm_path, pieces, [helm] if helm else [],
                           dyns=[(dyn_from_json(rec), cloth)])
    bb = mesh.get_bounding_box()
    log(f"mid {c['id']} bounds {bb.min} {bb.max}, slots "
        f"{len(mesh.get_editor_property('static_materials'))}")
    mesh.set_editor_property("nanite_settings", unreal.MeshNaniteSettings(enabled=False)) \
        if hasattr(unreal, "MeshNaniteSettings") else None
    # the bake: the body's skin drives every vertex (its nearest triangles), the walk at fps
    walk = unreal.load_asset(clips[SPEC["walks"][0]]["anim"])
    fac = unreal.DataAssetFactory()
    fac.set_editor_property("data_asset_class", unreal.AnimToTextureDataAsset)
    da = _asset(da_path, unreal.AnimToTextureDataAsset, fac)
    texs = {}
    for k in ("bone_position_texture", "bone_rotation_texture", "bone_weight_texture"):
        tp = f"{folder}/T_{c['id']}_{k.replace('_texture', '')}"
        texs[k] = _asset(tp, unreal.Texture2D, unreal.Texture2DFactoryNew())
    smes = unreal.get_editor_subsystem(unreal.StaticMeshEditorSubsystem)
    n_uv = smes.get_num_uv_channels(mesh, 0)
    info = unreal.AnimToTextureAnimSequenceInfo()
    info.set_editor_property("anim_sequence", walk)
    # (one loop of the clip at the bake's rate: AnimToTexture takes the clip's own key count,
    # its 30 fps keys, as the samples, which at 15 fps ran twice the clip's length and held its
    # last pose for the second half; lifegen_people_fixes)
    loop = max(2, int(round(unreal.AnimationLibrary.get_sequence_length(walk)
                            * float(SPEC["far"]["fps"]))))
    for k, v in (("use_custom_range", True), ("start_frame", 0), ("end_frame", loop - 1)):
        try:
            info.set_editor_property(k, v)
        except Exception as e:                                      # noqa: BLE001
            log(f"mid {c['id']}: the bake's range ({k}): {e}")
    for k, v in (("skeletal_mesh", body), ("skeletal_lod_index", _lod(body, lod - 2)),
                 ("static_mesh", mesh), ("static_lod_index", 0), ("uv_channel", min(3, n_uv)),
                 ("mode", unreal.AnimToTextureMode.BONE),
                 ("precision", unreal.AnimToTexturePrecision.SIXTEEN_BITS),
                 ("num_bone_influences", unreal.AnimToTextureNumBoneInfluences.FOUR),
                 ("sample_rate", float(SPEC["far"]["fps"])), ("anim_sequences", [info]),
                 ("auto_play", True), ("num_driver_triangles", 4), *texs.items()):
        da.set_editor_property(k, v)
    if not unreal.AnimToTextureBPLibrary.animation_to_texture(da):
        raise RuntimeError(f"{c['id']}: AnimToTexture's bake failed")
    # (the bone textures saved, then the data asset that names them: LG1's build saved only the
    # data asset, so on reload its textures and the mid materials' were the engine's default
    # texture and every mid person stood crouched with its arms out; lifegen_people_fixes)
    for k, t in texs.items():
        if not EAL.save_loaded_asset(t, False):
            raise RuntimeError(f"{c['id']}: the bake's {k} was not saved")
    EAL.save_loaded_asset(da, False)
    base = mid_material()
    mats = mesh.get_editor_property("static_materials")
    for i, sm_mat in enumerate(mats):
        src = sm_mat.get_editor_property("material_interface")
        mip = f"{folder}/MI_{lid}_Mid_{i}"
        mi = _asset(mip, unreal.MaterialInstanceConstant,
                    unreal.MaterialInstanceConstantFactoryNew())
        if src is not None and src.get_name().startswith("M_CgPersonMid") and src in cloth:
            MEL.set_material_instance_parent(mi, src)
            unreal.AnimToTextureBPLibrary.update_material_instance_from_data_asset(
                da, mi, unreal.MaterialParameterAssociation.GLOBAL_PARAMETER)
            EAL.save_loaded_asset(mi)
            mesh.set_material(i, mi)
            continue
        MEL.set_material_instance_parent(mi, base)
        tex, tint = _texture_of(src)
        if src is not None and "garment" in src.get_name().lower():
            MEL.set_material_instance_scalar_parameter_value(mi, "UseInstanceTint", 1.0)
        if src is not None and ("hair" in src.get_name().lower()
                                or src.get_path_name() in helm_mats):
            tex = None
            # (the groom's helmet carries no color of its own: a natural hair color by the
            # character, darker ones more often)
            h = HAIR_COLORS[int(c["index"] * 7 + 3) % len(HAIR_COLORS)]
            tint = unreal.LinearColor(h[0], h[1], h[2], 1.0)
        if tex is not None:
            tex = mid_texture(tex, folder)
            MEL.set_material_instance_texture_parameter_value(mi, "BaseColor", tex)
        MEL.set_material_instance_vector_parameter_value(mi, "Tint", tint)
        unreal.AnimToTextureBPLibrary.update_material_instance_from_data_asset(
            da, mi, unreal.MaterialParameterAssociation.GLOBAL_PARAMETER)
        EAL.save_loaded_asset(mi)
        mesh.set_material(i, mi)
    EAL.save_loaded_asset(mesh)
    nf = int(da.get_editor_property("num_frames"))
    # (the far card's walk is one stride of it: its sheet's frames span that)
    cyc = stride_period(walk)
    log(f"mid {c['id']}: {nf} frames, the walk {unreal.AnimationLibrary.get_sequence_length(walk)} s, "
        f"a stride {cyc} s")
    EAL.set_metadata_tag(da, "cg.cycle", str(cyc))
    tag(da, HASH)
    return {"mesh": sm_path, "start": 0, "end": nf - 1, "fps": float(SPEC["far"]["fps"]),
            "data": da_path, "cycle_s": cyc, "made": True}


def step_mid():
    out = {}
    made = 0
    for c, lk in look_list():
        sk = R["characters"][c["id"]]["skeleton"]
        out[lk["id"]] = mid_mesh(c, R["clip_groups"][sk]["clips"], lk)
        R.setdefault("looks", {}).setdefault(lk["id"], {})["mid"] = out[lk["id"]]
        log(f"mid {lk['id']}: {out[lk['id']]}")
        save_result()
        yield
        made += 1 if out[lk["id"]].get("made") else 0
        if made >= int(JOB.get("mid_per_run", 72)) and lk is not look_list()[-1][1]:
            R["restart"] = True
            return {"count": len(out), "restart": True}
    return {"count": len(out)}


