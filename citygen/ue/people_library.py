def _transfer(src, dst, target_bones):
    BW = unreal.GeometryScript_BoneWeights
    o = unreal.GeometryScriptTransferBoneWeightsOptions()
    o.set_editor_property("transfer_method", unreal.TransferBoneWeightsMethod.CLOSEST_POINT_ON_SURFACE)
    if target_bones:
        o.set_editor_property("output_target_mesh_bones", unreal.OutputTargetMeshBones.TARGET_BONES)
    BW.transfer_bone_weights_from_mesh(src, dst, o)


def skin_garment(dm, rec, src):
    """The garment's weights: the plain outfit's where it is nearer than the body (the body
    has no skin under it), else the body's; a vertex held to a bone blended toward it."""
    BW = unreal.GeometryScript_BoneWeights
    sp = unreal.GeometryScript_MeshSpatial
    LU = unreal.GeometryScript_List
    BW.copy_bones_from_mesh(src["body"], dm, unreal.GeometryScriptCopyBonesFromMeshOptions())
    other = unreal.DynamicMesh()
    unreal.GeometryScript_MeshEdits.append_mesh(other, dm, unreal.Transform())
    BW.copy_bones_from_mesh(src["body"], other, unreal.GeometryScriptCopyBonesFromMeshOptions())
    _transfer(src["body"], dm, True)
    _transfer(src["outfit"], other, True)
    pos = LU.convert_vector_list_to_array(_of(
        unreal.GeometryScript_MeshQueries.get_all_vertex_positions(dm, False),
        unreal.GeometryScriptVectorList))
    qo = unreal.GeometryScriptSpatialQueryOptions()
    bones = {}
    rb, rw = rec.get("rigid_bone") or [], rec.get("rigid_w") or []
    names = rec.get("bones") or []
    swapped = held = 0
    for i, p in enumerate(pos):
        dist = {}
        for k in ("body", "outfit"):
            r = sp.find_nearest_point_on_mesh(src[k], src["bvh"][k], p, qo)
            tp = _of(r, unreal.GeometryScriptTrianglePoint)
            dist[k] = (tp.position - p).length() if tp is not None else 1e9
        w = None
        if dist["outfit"] < dist["body"] - 0.3:
            w = list(_of(BW.get_vertex_bone_weights(other, i), list) or [])
            if w:
                BW.set_vertex_bone_weights(dm, i, w)
                swapped += 1
        if i < len(rb) and rb[i] >= 0 and i < len(rw) and rw[i] > 0.0:
            name = names[rb[i]]
            if name not in bones:
                bones[name] = _of(BW.get_bone_index(dm, name), int)
            bi = bones[name]
            if bi is not None and bi >= 0:
                cur = w or list(_of(BW.get_vertex_bone_weights(dm, i), list) or [])
                mine = [unreal.GeometryScriptBoneWeight(bone_index=bi, weight=1.0)]
                BW.set_vertex_bone_weights(dm, i, BW.blend_bone_weights(cur, mine, float(rw[i])))
                held += 1
    return {"outfit_weights": swapped, "held": held, "verts": len(pos)}


